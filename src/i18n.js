let currentLocale = "en";

export function resolveLocale(query = "", stored = "") {
  const requested = new URLSearchParams(query).get("lang");
  for (const value of [requested, stored]) {
    const code = String(value || "").toLowerCase().split(/[-_]/)[0];
    if (code in localeTags) return code;
  }
  return "en";
}

export function setLocale(locale) {
  currentLocale = locale in localeTags ? locale : "en";
  if (typeof document !== "undefined") document.documentElement.lang = localeTags[currentLocale];
}

export function getLocale() { return currentLocale; }
export function getLocaleTag() { return localeTags[currentLocale]; }

export function t(key, values = {}) {
  const template = messages[currentLocale]?.[key] ?? messages.en[key] ?? messages.ja[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}

export function translateStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((node) => { node.textContent = t(node.dataset.i18n); });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => { node.placeholder = t(node.dataset.i18nPlaceholder); });
  root.querySelectorAll("[data-i18n-aria]").forEach((node) => { node.setAttribute("aria-label", t(node.dataset.i18nAria)); });
  root.querySelectorAll("[data-i18n-content]").forEach((node) => { node.content = t(node.dataset.i18nContent); });
}

